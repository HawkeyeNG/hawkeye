export type Minor = { name: string; party: string; meta?: string };

/**
 * Where a race sits on the map — the same block app/race.js reads.
 *
 * A race declares its own seat, so the region -> race-page index can be derived
 * rather than kept as a second list beside the data. `level` picks the geometry:
 * a governorship is a `state` (drawn as its LGAs), a Senate seat is
 * `senatorial`, a House seat `federal_constituency`.
 */
export type RaceJoin = {
  contest?: string;
  /**
   * `lga` is the STATE-ASSEMBLY level. State constituencies are not a column in
   * the electoral register — which is why the backend buckets an SHA contest's
   * reports by LGA — so an assembly seat's map, board and scope all key on the
   * LGA it sits in. There is no outline file for one, and there cannot be.
   */
  level: 'state' | 'senatorial' | 'federal_constituency' | 'lga';
  value: string;
  state?: string;
  lgas?: string[];
};

export type Race = {
  asOf?: string;
  office?: string;
  election?: string;
  date?: string;
  /** Verbatim date label when there is no fixed ISO date yet (e.g. the 2027
   *  presidential day, shown as dateText "2027" / dateLabel "Election year"). */
  dateText?: string;
  dateLabel?: string;
  note?: string;
  photoCredit?: string;
  incumbentNote?: string;
  notableAbsence?: string;
  /**
   * `wards` is what a SEAT is measured in. The LGA count describes a
   * governorship and a senatorial district well and a federal constituency
   * badly (2-4); for a state constituency it is almost always the number 1.
   * Both are carried and the card picks by `join.level` — see components/race.
   */
  stats?: {
    lgas?: number;
    wards?: number;
    pollingUnits?: number;
    candidates?: number;
    heldBy?: string;
    /** These figures cover more than this one seat — see SeatInfo. */
    sharedRegister?: boolean;
  };
  candidates: Candidate[];
  others?: Candidate[];
  minors?: Minor[];
  join?: RaceJoin;
  /**
   * What the electoral commission ANNOUNCED, recorded by hand from the returning
   * officer's declaration. Not derivable: IReV publishes photographs of EC8A
   * sheets, never numbers, so there is no endpoint to read this from — an absent
   * block means nobody has recorded the declaration, not that a race is
   * undecided. Kept separate from `candidates` because this is someone else's
   * claim that Hawkeye is citing, not Hawkeye's own count.
   */
  declared?: {
    by?: string;
    date?: string;
    place?: string;
    returningOfficer?: string;
    winner: string;
    party?: string;
    votes?: number;
    runnerUp?: { name: string; party: string; votes: number };
    results?: { party: string; name?: string; votes: number }[];
    lgasWon?: Record<string, number>;
    sources?: string[];
    note?: string;
  };
};

