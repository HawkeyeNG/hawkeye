/**
 * Pre-fetch the ML Kit document-scanner Play services module at app start.
 *
 * ── THE BUG THIS EXISTS FOR ───────────────────────────────────────────────
 *
 * `react-native-document-scanner-plugin` depends on
 * `com.google.android.gms:play-services-mlkit-document-scanner`, which is an
 * ON-DEMAND Play services module: the scanner UI and its models are not in the
 * APK at all. Google Play services fetches them the first time an app asks to
 * scan.
 *
 * On the build currently on Play, that fetch never completes. Tapping scan puts
 * the observer on Google's own "Downloading updates to Google Play services…"
 * dialog, which offers nothing but Cancel — and cancelling reports the same
 * status as deliberately backing out of a working scanner, so the app cannot
 * tell the two apart from the result alone (see lib/scan.ts).
 *
 * ── WHAT THIS DOES ────────────────────────────────────────────────────────
 *
 * Asks Play services to install the module in the BACKGROUND when the app
 * starts, using ModuleInstallClient.deferredInstall(). By the time anyone
 * reaches the report screen the module is normally already there, and the
 * download — if it happens at all — happens while they are reading the home
 * screen rather than while they are standing at a polling unit holding a sheet.
 *
 * deferredInstall, not installModules: deferred is a low-priority background
 * request with NO UI. installModules can surface Google's dialog, which is the
 * exact thing being avoided. If the deferred request fails there is nothing to
 * show and nothing to handle — the app is no worse off than before, and
 * lib/scan.ts still falls back to the plain camera.
 *
 * ── WHY A CONFIG PLUGIN ───────────────────────────────────────────────────
 *
 * `native/android` is gitignored and regenerated by `expo prebuild`, so an
 * edit made directly to MainApplication.kt is deleted by the next prebuild —
 * silently, and only noticed when the bug comes back. Everything that has to
 * survive lives in plugins/, which is why with-allow-backup-override and
 * with-release-signing are there too.
 *
 * ── DISABLED 2026-08-23: IT DOES NOT COMPILE ──────────────────────────────
 *
 * Removed from app.json's plugins array. Re-enabling it as-is fails the build:
 *
 *   :app:compileReleaseKotlin
 *   e: MainApplication.kt:5:48 Unresolved reference 'GmsDocumentScannerOptions'
 *   e: MainApplication.kt:6:48 Unresolved reference 'GmsDocumentScanning'
 *   BUILD FAILED in 25m 3s
 *
 * The scanner artifact is declared implementation-scoped inside the
 * react-native-document-scanner-plugin library, so it is on that module's
 * compile path and not on the app module's. The imports this plugin injects into
 * MainApplication.kt therefore cannot resolve.
 *
 * TO REVIVE IT, two things, in this order:
 *   1. Have the plugin also add the dependency to the APP module, e.g. via
 *      withAppBuildGradle appending
 *      `implementation 'com.google.android.gms:play-services-mlkit-document-scanner:...'`
 *      at the version the library already resolves, so the two cannot diverge.
 *   2. Prove it on a phone that currently reproduces the stall. Compiling is not
 *      the same as fixing; scannerLastError() in lib/scan.ts exists to say which
 *      it is.
 *
 * Until both are done this stays out of release builds. The scanner stall it
 * targets is present in the live listing too, so shipping without it is not a
 * regression — it is the status quo, minus twenty-five minutes of failed build.
 *
 * ── NOT VERIFIED ON A DEVICE ──────────────────────────────────────────────
 *
 * This is a candidate fix, not a confirmed one. It compiles or it does not, and
 * that much a build will tell you — but whether it actually resolves the stall
 * can only be established by installing the resulting AAB on a phone that
 * currently reproduces the bug and tapping scan. `scannerLastError()` in
 * lib/scan.ts was added to capture the underlying exception for exactly this
 * reason: if the module still fails, that message says whether it is absent,
 * out of storage, or a Play services version floor.
 */
const { withMainApplication } = require('@expo/config-plugins');

const IMPORTS = [
  'import com.google.android.gms.common.moduleinstall.ModuleInstall',
  'import com.google.android.gms.common.moduleinstall.ModuleInstallRequest',
  'import com.google.mlkit.vision.documentscanner.GmsDocumentScannerOptions',
  'import com.google.mlkit.vision.documentscanner.GmsDocumentScanning',
];

const PREWARM = `
    // Hawkeye: pre-fetch the ML Kit document-scanner Play services module.
    // Background, no UI, best-effort. See plugins/with-mlkit-scanner-prewarm.js.
    try {
      val scannerOptions = GmsDocumentScannerOptions.Builder()
        .setPageLimit(1)
        .setResultFormats(GmsDocumentScannerOptions.RESULT_FORMAT_JPEG)
        .build()
      ModuleInstall.getClient(this)
        .deferredInstall(GmsDocumentScanning.getClient(scannerOptions))
    } catch (t: Throwable) {
      // A pre-warm that fails must never stop the app starting; the scanner
      // path already degrades to the plain camera on its own.
    }
`;

module.exports = function withMlkitScannerPrewarm(config) {
  return withMainApplication(config, (cfg) => {
    let src = cfg.modResults.contents;

    if (src.includes('deferredInstall')) return cfg; // already applied

    if (cfg.modResults.language !== 'kt') {
      // Java MainApplication would need different syntax. Fail loudly rather
      // than injecting Kotlin into a Java file and breaking the build in a way
      // that looks unrelated to this plugin.
      throw new Error(
        'with-mlkit-scanner-prewarm expects a Kotlin MainApplication; got '
        + `${cfg.modResults.language}. Update the plugin before shipping.`,
      );
    }

    // Imports go after the package line, which is always first.
    const missing = IMPORTS.filter((i) => !src.includes(i));
    if (missing.length) {
      src = src.replace(/^(package .*\n)/m, `$1\n${missing.join('\n')}\n`);
    }

    // Inject at the END of onCreate so it runs after React Native is up and
    // cannot delay first frame.
    const onCreate = /(override fun onCreate\(\) \{[\s\S]*?super\.onCreate\(\)\n)/;
    if (!onCreate.test(src)) {
      throw new Error('with-mlkit-scanner-prewarm could not find onCreate() in MainApplication.kt');
    }
    src = src.replace(onCreate, `$1${PREWARM}`);

    cfg.modResults.contents = src;
    return cfg;
  });
};
